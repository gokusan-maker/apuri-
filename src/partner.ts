// 正解したときの追加ダメージ（n は何問目の正解か）
export function skillDamage(skill: SkillId, n: number, lv = 1): number {
  if (skill === 'fire') return lv >= 3 ? 5 : 3
  if (skill === 'foxfire' && n % 3 === 0) return lv >= 3 ? 8 : 5
  return 0
}

